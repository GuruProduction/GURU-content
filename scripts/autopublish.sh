# THE AUTOPUBLISH LOOP.
#
# The superadmin panel writes rows to Postgres and nothing else. This script
# closes the gap between that and the public record: it checks whether the live
# content differs from what is committed here, and if it does, publishes,
# commits and pushes. Run it on a timer and the repo follows the panel with no
# human in the loop.
#
# WHY A POLL RATHER THAN A HOOK IN THE SERVER. The server could call this after
# every write, but that means editing the write handlers, and the correct
# behaviour if the publish fails is not to fail the write: the content is
# already live in the database by then and the panel should not report an error
# for a record that is one commit behind. Polling makes the two independent, so
# a broken repository cannot break the panel, and a broken panel cannot stop the
# record catching up.
#
# WHAT IT REFUSES TO DO. It never forces a push, never rewrites history, and
# never publishes when the database is unreachable. If the check fails because
# Postgres is down, it exits quietly and tries again next tick, because a publish
# from a half-read database would delete every file the query did not return.
#
# EXIT CODES
#   0  nothing to do, or published successfully
#   1  a publish was needed and failed
#   2  could not determine state; nothing was written

set -uo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO" || exit 2

LOG="$REPO/.autopublish.log"

log() {
  printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG"
}

# Rotate the log so it cannot grow without bound on a machine that never reboots.
if [ -f "$LOG" ] && [ "$(wc -c < "$LOG" | tr -d ' ')" -gt 262144 ]; then
  tail -n 500 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
fi

# 1. Is the database there at all? A failed read must never be mistaken for an
#    empty one, because an empty read would delete every published file.
if ! docker exec guru-postgres psql -U guru_app -d guru_server -t -A -c "select 1" >/dev/null 2>&1; then
  exit 2
fi

# 2. Does the live content differ from what is committed?
if node scripts/publish.mjs --check >/dev/null 2>&1; then
  exit 0
fi

# 3. Publish, and capture what it says so a failure is diagnosable later.
if ! OUT=$(node scripts/publish.mjs 2>&1); then
  log "publish FAILED: $OUT"
  exit 1
fi
log "published: $(printf '%s' "$OUT" | tr '\n' ' ')"

# 4. Commit only if something actually changed on disk. `git add -A` here is
#    safe because every path it can touch is generated by the publish above.
if git diff --quiet && git diff --cached --quiet; then
  exit 0
fi

BUNDLE=$(node -e 'process.stdout.write(require("./manifest.json").bundle_version)')
COUNTS=$(node -e 'const m=require("./manifest.json");process.stdout.write(Object.entries(m.counts).filter(([k])=>k!=="total").map(([k,v])=>v+" "+k).join(", "))')

git add -A
git -c user.name="Unus Lumen" -c user.email="devloper@unuslumen.com" \
  commit -q -m "content: publish $BUNDLE from the live database

Published by the autopublish loop after a panel change.

$COUNTS.

Bundle $BUNDLE."

# 5. Push. A failure here leaves the commit local and is retried on the next
#    tick, which is why the check above compares against the database rather
#    than against the remote.
if ! PUSH=$(git push origin HEAD 2>&1); then
  log "commit $BUNDLE made but push FAILED: $PUSH"
  exit 1
fi

log "pushed $BUNDLE"
exit 0
